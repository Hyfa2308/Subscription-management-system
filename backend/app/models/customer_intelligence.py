"""
REVORA – Customer Intelligence & Churn Prediction ORM Models.
Stores calculated customer health scores, churn risk assessments,
retention recommendations, and telemetry data.
"""

from __future__ import annotations

import enum
from datetime import datetime
from typing import Any

from sqlalchemy import (
    Boolean, DateTime, Float, ForeignKey, Integer, JSON, String, Text, func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.session import Base


class HealthCategory(str, enum.Enum):
    HEALTHY           = "healthy"             # 75 - 100
    NEEDS_ATTENTION   = "needs_attention"     # 50 - 74
    AT_RISK           = "at_risk"             # 0 - 49
    INSUFFICIENT_DATA = "insufficient_data"   # Missing critical operational data


class ChurnRiskCategory(str, enum.Enum):
    LOW_RISK          = "low_risk"            # 0 - 34
    MEDIUM_RISK       = "medium_risk"         # 35 - 69
    HIGH_RISK         = "high_risk"           # 70 - 100
    INSUFFICIENT_DATA = "insufficient_data"   # Not enough telemetry to assess


class RecommendationPriority(str, enum.Enum):
    HIGH   = "high"
    MEDIUM = "medium"
    LOW    = "low"


class RecommendationStatus(str, enum.Enum):
    PENDING     = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED   = "completed"
    DISMISSED   = "dismissed"


class CustomerHealthScore(Base):
    """
    Stores explainable customer health score calculations.
    Includes sub-scores for payment reliability, subscription stability,
    renewal behaviour, customer tenure, and revenue consistency.
    """
    __tablename__ = "customer_health_scores"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    customer_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("customers.id", ondelete="CASCADE"), nullable=False, index=True,
    )

    # Health score (0-100) or None if insufficient data
    score: Mapped[float | None] = mapped_column(Float, nullable=True)
    category: Mapped[str] = mapped_column(String(50), nullable=False, default=HealthCategory.INSUFFICIENT_DATA.value)

    # Component sub-scores (0-100 or None if missing)
    payment_reliability_score:    Mapped[float | None] = mapped_column(Float, nullable=True)
    subscription_stability_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    renewal_behaviour_score:      Mapped[float | None] = mapped_column(Float, nullable=True)
    customer_tenure_score:        Mapped[float | None] = mapped_column(Float, nullable=True)
    revenue_consistency_score:    Mapped[float | None] = mapped_column(Float, nullable=True)

    # Explainability breakdown: stored as JSON lists of factor descriptions
    positive_factors: Mapped[list[str]] = mapped_column(JSON, default=list, nullable=False)
    negative_factors: Mapped[list[str]] = mapped_column(JSON, default=list, nullable=False)

    # Methodology & audit
    formula_version: Mapped[str] = mapped_column(String(30), default="1.0.0", nullable=False)
    weights_used:    Mapped[dict[str, float]] = mapped_column(JSON, default=dict, nullable=False)
    is_data_sufficient: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    missing_data_fields: Mapped[list[str]] = mapped_column(JSON, default=list, nullable=False)

    calculated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    customer: Mapped["Customer"] = relationship("Customer")  # type: ignore # noqa: F821

    def __repr__(self) -> str:
        return f"<CustomerHealthScore customer_id={self.customer_id} score={self.score} category={self.category}>"


class CustomerChurnAssessment(Base):
    """
    Stores churn risk assessments generated by the rule-based churn engine.
    Structured to be modular for drop-in ML model replacement.
    """
    __tablename__ = "customer_churn_assessments"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    customer_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("customers.id", ondelete="CASCADE"), nullable=False, index=True,
    )

    # Churn risk probability score (0-100, where 100 is maximum risk) or None
    risk_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    risk_category: Mapped[str] = mapped_column(String(50), nullable=False, default=ChurnRiskCategory.LOW_RISK.value)

    # Detailed contributing factors list: [{ "factor": "...", "severity": "high", "impact": 25, "description": "..." }]
    contributing_factors: Mapped[list[dict[str, Any]]] = mapped_column(JSON, default=list, nullable=False)
    explanation: Mapped[str] = mapped_column(Text, nullable=False)
    recommended_action: Mapped[str] = mapped_column(Text, nullable=False)

    engine_version: Mapped[str] = mapped_column(String(50), default="rule_based_v1", nullable=False)
    assessment_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    customer: Mapped["Customer"] = relationship("Customer")  # type: ignore # noqa: F821

    def __repr__(self) -> str:
        return f"<CustomerChurnAssessment customer_id={self.customer_id} risk_score={self.risk_score} risk_category={self.risk_category}>"


class RetentionRecommendation(Base):
    """
    Actionable retention recommendations generated for customers.
    Requires user confirmation before applying actions.
    """
    __tablename__ = "retention_recommendations"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    customer_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("customers.id", ondelete="CASCADE"), nullable=False, index=True,
    )

    recommendation_type: Mapped[str] = mapped_column(String(80), nullable=False)
    reason:              Mapped[str] = mapped_column(Text, nullable=False)
    priority:            Mapped[str] = mapped_column(String(20), default=RecommendationPriority.MEDIUM.value, nullable=False)
    suggested_action:    Mapped[str] = mapped_column(Text, nullable=False)
    expected_benefit:    Mapped[str | None] = mapped_column(Text, nullable=True)

    status: Mapped[str] = mapped_column(
        String(30), default=RecommendationStatus.PENDING.value, nullable=False, index=True,
    )

    # Audit & execution trace
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
    executed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    executed_by: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True,
    )
    execution_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    customer: Mapped["Customer"] = relationship("Customer")  # type: ignore # noqa: F821

    def __repr__(self) -> str:
        return f"<RetentionRecommendation id={self.id} customer_id={self.customer_id} priority={self.priority} status={self.status}>"


class CustomerTelemetry(Base):
    """
    Customer telemetry record for subscription behaviour, payment history,
    and revenue metrics. Clearly distinguishes between real database metrics
    and labelled demo telemetry.
    """
    __tablename__ = "customer_telemetry"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    customer_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("customers.id", ondelete="CASCADE"), unique=True, nullable=False, index=True,
    )

    # Subscription telemetry
    active_subscriptions:   Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    paused_subscriptions:   Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    closed_subscriptions:   Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    renewal_count:          Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    upcoming_expirations:   Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    days_to_expiration:     Mapped[int | None] = mapped_column(Integer, nullable=True)
    avg_duration_days:      Mapped[float | None] = mapped_column(Float, nullable=True)
    has_auto_renew:         Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    # Payment telemetry
    total_payments:         Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    successful_payments:    Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    failed_payments:        Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    delayed_payments:       Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    outstanding_invoices_amount: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    overdue_invoices_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    avg_payment_delay_days: Mapped[float | None] = mapped_column(Float, nullable=True)
    days_since_last_payment: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # Revenue contribution
    monthly_recurring_revenue:  Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    total_historical_revenue:   Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    avg_subscription_value:     Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    revenue_trend:              Mapped[str] = mapped_column(String(30), default="stable", nullable=False)  # growing, stable, declining

    # Data source transparency: "real_database" vs "demo_telemetry"
    data_source: Mapped[str] = mapped_column(String(50), default="real_database", nullable=False)
    is_demo_data: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    customer: Mapped["Customer"] = relationship("Customer")  # type: ignore # noqa: F821

    def __repr__(self) -> str:
        return f"<CustomerTelemetry customer_id={self.customer_id} source={self.data_source} is_demo={self.is_demo_data}>"
